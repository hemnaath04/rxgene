"""Generate the demo narration with ElevenLabs (Eleven v3, emotion tags), one file per section.

Reads scripts/voiceover_sections.json and writes media/voice/S1.mp3 ... S11.mp3 plus
media/timing.md (each section's duration, used to size the screen clips). media/ is git-ignored.

API key: put it in media/.elevenlabs_key (one line) or ELEVENLABS_API_KEY. Never commit it.

Usage:
  python3 scripts/make_voiceover.py --list-voices             # pick a narrator
  python3 scripts/make_voiceover.py --voice <voice_id>         # all sections
  python3 scripts/make_voiceover.py --voice <id> --only S2 S7  # retake some sections
"""
import argparse
import json
import os
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MEDIA = ROOT / "media"
API = "https://api.elevenlabs.io"


def api_key():
    key = os.environ.get("ELEVENLABS_API_KEY")
    keyfile = MEDIA / ".elevenlabs_key"
    if not key and keyfile.exists():
        key = keyfile.read_text().strip()
    if not key:
        sys.exit("No API key: put it in media/.elevenlabs_key or set ELEVENLABS_API_KEY.")
    return key


def curl(args):
    # curl instead of urllib: python.org builds on macOS often lack root certs.
    out = subprocess.run(["curl", "-sS", "-w", "\n%{http_code}", *args], capture_output=True)
    body, _, code = out.stdout.rpartition(b"\n")
    return int(code or 0), body


def list_voices(key):
    code, body = curl(["-H", f"xi-api-key: {key}", f"{API}/v1/voices"])
    if code != 200:
        sys.exit(f"voices: HTTP {code} {body[:300]!r}")
    for v in json.loads(body).get("voices", []):
        labels = v.get("labels") or {}
        print(f"{v['voice_id']}  {v['name']:<22} {labels.get('gender', ''):<7} {labels.get('accent', ''):<12} {labels.get('description', '') or labels.get('use_case', '')}")


def duration(path):
    out = subprocess.run(["afinfo", str(path)], capture_output=True, text=True).stdout
    for line in out.splitlines():
        if "estimated duration" in line:
            return float(line.split(":")[1].split()[0])
    return 0.0


def generate(key, voice, only, stability, speed):
    sections = json.loads((ROOT / "scripts" / "voiceover_sections.json").read_text())["sections"]
    outdir = MEDIA / "voice"
    outdir.mkdir(parents=True, exist_ok=True)
    for s in sections:
        if only and s["id"] not in only:
            continue
        body = {"text": s["text"], "model_id": "eleven_v3",
                "voice_settings": {"stability": stability, "speed": speed}}
        out = outdir / f"{s['id']}.mp3"
        code, audio = curl(["-X", "POST", "-H", f"xi-api-key: {key}", "-H", "Content-Type: application/json",
                            "--data", json.dumps(body),
                            f"{API}/v1/text-to-speech/{voice}?output_format=mp3_44100_128"])
        if code != 200:
            sys.exit(f"{s['id']}: HTTP {code} {audio[:300]!r}")
        out.write_bytes(audio)
        print(f"{s['id']} {s['name']:<11} {duration(out):5.1f}s  -> {out.relative_to(ROOT)}")

    rows, total = [], 0.0
    for s in sections:
        f = outdir / f"{s['id']}.mp3"
        d = duration(f) if f.exists() else 0.0
        rows.append(f"| {s['id']} | {s['name']} | {d:.1f} | {total:.1f} | {total + d:.1f} |")
        total += d
    (MEDIA / "timing.md").write_text(
        "# Narration timing (generated by scripts/make_voiceover.py)\n\n"
        "Record each screen clip at least duration + 3 s. Start/end are positions in the\n"
        "assembled narration (sections back to back, before any gaps the editor adds).\n\n"
        "| Section | Name | Duration (s) | Start (s) | End (s) |\n|---|---|---|---|---|\n"
        + "\n".join(rows) + f"\n\n**Total: {total:.1f} s** (limit 180 s)\n")
    print(f"total {total:.1f}s -> media/timing.md")


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--list-voices", action="store_true")
    p.add_argument("--voice")
    p.add_argument("--only", nargs="*")
    p.add_argument("--stability", type=float, default=0.5, help="v3: 0.0 creative, 0.5 natural, 1.0 robust")
    p.add_argument("--speed", type=float, default=1.0)
    a = p.parse_args()
    k = api_key()
    if a.list_voices:
        list_voices(k)
    elif a.voice:
        generate(k, a.voice, a.only, a.stability, a.speed)
    else:
        p.print_help()
